        '```',
        '',
        'Lê-se: "o valor é 100 ou mais? então 0, senão 15".',
        '',
        'E quando você compara **uma mesma variável** com vários valores fixos, o `switch` fica mais limpo que uma escada de `else if`. Ele compara com `===`:',
